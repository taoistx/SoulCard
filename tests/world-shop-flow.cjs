const assert = require("node:assert/strict");
const path = require("node:path");
const os = require("node:os");

(async () => {
  const { browser, page, errors, seed, snapshot, button, dismiss, inspect, rest, fresh, move, finishBattle } = await require("./sediment-browser.cjs")();
  const open = () => button("逛艾迪的货摊").click();
  const select = (id) => page.locator(`[data-shop-offer="${id}"]`).click();
  const buy = () => page.click("#shopExchangeButton");
  const close = () => page.click("#closeShopButton");
  try {
    await fresh(); await move("eddie"); await open();
    assert.equal(await page.locator("#worldModal").isVisible(), false);
    assert.equal(await page.locator("#shopExchangeButton").isDisabled(), true);
    assert.match(await page.locator("#shopExchangeButton").innerText(), /新鲜血肉不足/);
    const empty = await snapshot();
    assert.equal(await page.evaluate(() => exchangeShopOffer("eddie", "daily_equipment").ok), false);
    assert.deepEqual(await snapshot(), empty);
    await page.keyboard.press("l"); await page.keyboard.press("i"); await page.keyboard.press("e");
    assert.deepEqual(await snapshot(), empty);
    assert.equal(await page.locator("#characterPanel").isVisible(), false);
    await page.keyboard.press("Shift+Tab");
    assert.equal(await page.evaluate(() => document.activeElement.dataset.shopOffer), "work_cover");
    await page.keyboard.press("Escape"); assert.equal(await page.locator("#shopPanel").isVisible(), false);
    console.log("PASS direct camp entry, insufficient resources, modal hotkeys, keyboard focus and Escape");

    await seed("eddie", {}, { freshFlesh: 2, mistWrapMaterial: 2 }); await open();
    const before = await snapshot();
    await page.screenshot({ path: path.join(os.tmpdir(), "eddie-shop-desktop.png") });
    await buy();
    let state = await snapshot();
    assert.equal(state.inventory.longSword, 1); assert.equal(state.inventory.freshFlesh, 1);
    assert.equal(state.flags.eddieTradeDone, true);
    assert.equal(state.day, before.day); assert.equal(state.stamina, before.stamina); assert.deepEqual(state.deck, before.deck);
    assert.match(await page.locator("#shopFeedback").innerText(), /长剑已放入背包/);
    assert.equal(await page.evaluate(() => exchangeShopOffer("eddie", "daily_equipment").ok), false);
    assert.deepEqual(await snapshot(), state);
    await select("mist_wrap"); await buy();
    state = await snapshot(); assert.equal(state.inventory.eddieMistWrap, 1); assert.equal(state.flags.materialUse, "wrap");
    await select("work_cover"); await buy();
    state = await snapshot(); assert.equal(state.inventory.mistWrapMaterial, undefined);
    assert.equal(state.flags.eddieWorkProtected, true); assert.equal(state.flags.materialUse, "both");
    await close(); await inspect();
    assert.match(await page.locator("#worldModalBody").innerText(), /作业位支起了你留下的罩膜/);
    await button("与艾迪交谈").click(); await button("这里是什么地方？").click();
    assert.match(await page.locator("#worldModalBody").innerText(), /教堂/);
    await button("你是谁？").click(); await button("继续交易").click();
    assert.equal(await page.locator("#shopPanel").isVisible(), true);
    assert.equal(await page.locator("#shopExchangeButton").isDisabled(), true);
    await close(); await rest(); await inspect(); await open();
    assert.equal(await page.locator("#shopOfferName").innerText(), "井盖盾");
    assert.equal(await page.locator("#shopExchangeButton").innerText(), "本局已兑换");
    await select("mist_wrap"); assert.equal(await page.locator("#shopExchangeButton").isDisabled(), true);
    await close(); await page.click("#characterButton");
    await page.locator('[data-equip-item="longSword"][data-equip-slot="leftHand"]').click();
    await page.locator('[data-equip-item="eddieMistWrap"]').click();
    assert.equal((await snapshot()).equipment.leftHand, "longSword");
    assert.equal((await snapshot()).equipment.head, "eddieMistWrap");
    await page.click("#closeCharacterButton");
    console.log("PASS independent settlement, no double spend, crafted goods/equipment, service consequences, dialogue entry and rest limits");

    await seed("eddie", {}, { freshFlesh: 1, mistWrapMaterial: 1 }); await open();
    await page.evaluate(() => removeItem("freshFlesh"));
    await buy(); assert.match(await page.locator("#shopFeedback").innerText(), /不足/);
    assert.equal((await snapshot()).inventory.longSword, undefined);
    await select("work_cover"); await buy();
    assert.equal((await snapshot()).flags.materialUse, "work");
    await select("mist_wrap"); assert.equal(await page.locator("#shopExchangeButton").isDisabled(), true);
    await page.evaluate(() => { addItem("mistWrapMaterial"); renderWorldShop(); }); await buy();
    assert.equal((await snapshot()).flags.materialUse, "both");
    await close(); await rest(); await inspect(); await open();
    await page.evaluate(() => { addItem("freshFlesh"); renderWorldShop(); }); await buy();
    assert.equal((await snapshot()).inventory.shield, 1);
    console.log("PASS stale resource revalidation, shared material consumption and unspent Day 2 stock");

    await seed("eddie", {}, { freshFlesh: 1, mistWrapMaterial: 1 });
    await button("与艾迪交谈").click();
    assert.equal(await button(/鲜肉换当日装备|试制整套防护|留一片罩布/).count(), 0);
    await button("看看你的货物").click();
    await page.setViewportSize({ width: 390, height: 844 });
    await select("mist_wrap");
    await page.screenshot({ path: path.join(os.tmpdir(), "eddie-shop-mobile.png") });
    const bounds = await page.locator(".shop-card").boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390);
    assert.equal(await page.locator(".shop-card").evaluate((el) => el.scrollWidth <= el.clientWidth), true);
    await buy(); assert.equal((await snapshot()).inventory.eddieMistWrap, 1);
    await page.keyboard.press("Escape");
    await page.setViewportSize({ width: 1440, height: 1000 });
    await inspect(); await button("与艾迪交谈").click(); await button(/袭击艾迪/).click();
    await page.waitForFunction(() => state?.active); await finishBattle("Escape"); await dismiss(); await inspect(); await open();
    assert.equal(await page.locator("#shopPanel").isVisible(), true); await close();
    await inspect(); await button("与艾迪交谈").click(); await button(/袭击艾迪/).click();
    await page.waitForFunction(() => state?.active); await finishBattle("Win"); await dismiss(); await inspect();
    assert.equal(await button("逛艾迪的货摊").count(), 0);
    assert.equal(await page.evaluate(() => openWorldShop("eddie")), false);
    await fresh(); assert.equal(await page.locator("#shopPanel").isVisible(), false);
    assert.equal((await snapshot()).flags.eddieTradeDone, undefined);
    assert.deepEqual(errors, []);
    console.log("PASS NPC shop entry, mobile layout, battle escape/win return, dead merchant and new-run reset");
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
